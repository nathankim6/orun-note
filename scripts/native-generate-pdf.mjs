import fs from 'node:fs';
import { deflateSync } from 'node:zlib';
// Deterministic synthetic vector load, never a student document.
const paths = Array.from({ length: 100000 }, (_, i) => {
  const x = (i * 37) % 590, y = (i * 53) % 780;
  return `${x} ${y} m ${x + 9} ${y + 15} ${x + 3} ${y + 6} ${x + 1} ${y + 9} c S\n`;
}).join('');
const compressed = deflateSync(Buffer.from('0.15 0.35 0.65 RG 0.2 w\n' + paths));
const simple = 'BT /F1 18 Tf 50 700 Td (Synthetic QA reading page - no private data) Tj ET\n';
const objects = [
  '<< /Type /Catalog /Pages 2 0 R >>',
  '<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 >>',
  '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 5 0 R /Resources << >> >>',
  '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 6 0 R /Resources << /Font << /F1 7 0 R >> >> >>',
  Buffer.concat([Buffer.from(`<< /Length ${compressed.length} /Filter /FlateDecode >>\nstream\n`), compressed, Buffer.from('\nendstream')]),
  `<< /Length ${Buffer.byteLength(simple)} >>\nstream\n${simple}endstream`,
  '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
];
let out = Buffer.from('%PDF-1.4\n'); const offsets = [0];
objects.forEach((obj, i) => { offsets.push(out.length); out = Buffer.concat([out, Buffer.from(`${i + 1} 0 obj\n`), Buffer.from(obj), Buffer.from('\nendobj\n')]); });
const xref = out.length;
out = Buffer.concat([out, Buffer.from(`xref\n0 8\n0000000000 65535 f \n${offsets.slice(1).map(n => String(n).padStart(10, '0') + ' 00000 n \n').join('')}trailer\n<< /Size 8 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`)]);
fs.mkdirSync('qa/fixtures', { recursive: true });
fs.writeFileSync('qa/fixtures/pdf.generated.ts', `// Generated by scripts/native-generate-pdf.mjs. Synthetic only.\nexport const PDF_BASE64 = '${out.toString('base64')}';\n`);
console.log(`Synthetic two-page PDF: ${out.length} bytes, 100000 vector paths`);
