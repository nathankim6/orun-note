// Synthetic resolution target for the viewer lab (qa/lab). Never a student document.
// Page 1 carries five vertical bar gratings of known bar width: how many of them the screen still resolves tells which
// raster (reading / detail / zoom image / vector tile) the app is really showing at a given magnification.
import fs from 'node:fs';
const W = 612, H = 792;
const BARS = [0.2, 0.3, 0.45, 0.7, 1.0];           // bar width in pt (period = 2 × bar)
const SIZE = 24, GAP = 6, TOP = 230;                // each grating is SIZE × SIZE pt, top edge TOP pt below the page top
const x0 = W / 2 - (BARS.length * SIZE + (BARS.length - 1) * GAP) / 2;
const gratings = BARS.map((bar, i) => ({ bar, x: x0 + i * (SIZE + GAP), y: TOP, w: SIZE, h: SIZE }));
let c = '0 0 0 rg 0 0 0 RG\n';
for (const g of gratings) { for (let x = g.x; x + g.bar <= g.x + g.w + 1e-6; x += 2 * g.bar) c += `${x.toFixed(4)} ${(H - g.y - g.h).toFixed(4)} ${g.bar.toFixed(4)} ${g.h} re f\n`; }
const text = (size, y, s) => `BT /F1 ${size} Tf 60 ${H - y} Td (${s}) Tj ET\n`;
c += text(14, 80, 'Viewer lab resolution target - synthetic, no private data');
c += text(5, 300, 'The quick brown fox jumps over the lazy dog 0123456789 - five point text for zoomed reading');
c += text(7, 316, 'The quick brown fox jumps over the lazy dog 0123456789 - seven point');
c += text(9, 336, 'The quick brown fox jumps over the lazy dog 0123456789 - nine');
c += text(12, 360, 'The quick brown fox jumps over the lazy dog - twelve');
c += '0.2 w\n'; for (let i = 0; i <= 40; i++) c += `${60 + i * 3} 380 m ${60 + i * 3} 420 l S\n`;   // hairline comb
c += '0.6 w 40 40 532 712 re S\n';
const page2 = text(18, 100, 'Viewer lab page two - synthetic') + text(10, 140, 'Second page for page-turn and prefetch checks.');
const objects = [
  '<< /Type /Catalog /Pages 2 0 R >>',
  '<< /Type /Pages /Kids [3 0 R 4 0 R] /Count 2 >>',
  `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] /Contents 5 0 R /Resources << /Font << /F1 7 0 R >> >> >>`,
  `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${W} ${H}] /Contents 6 0 R /Resources << /Font << /F1 7 0 R >> >> >>`,
  `<< /Length ${Buffer.byteLength(c)} >>\nstream\n${c}endstream`,
  `<< /Length ${Buffer.byteLength(page2)} >>\nstream\n${page2}endstream`,
  '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
];
let out = Buffer.from('%PDF-1.4\n'); const offsets = [0];
objects.forEach((obj, i) => { offsets.push(out.length); out = Buffer.concat([out, Buffer.from(`${i + 1} 0 obj\n`), Buffer.from(obj), Buffer.from('\nendobj\n')]); });
const xref = out.length;
out = Buffer.concat([out, Buffer.from(`xref\n0 8\n0000000000 65535 f \n${offsets.slice(1).map(n => String(n).padStart(10, '0') + ' 00000 n \n').join('')}trailer\n<< /Size 8 /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`)]);
fs.mkdirSync('qa/lab', { recursive: true });
fs.writeFileSync('qa/lab/pdf.generated.ts', `// Generated by scripts/lab-generate-pdf.mjs. Synthetic only.\nexport const LAB_PDF_BASE64 = '${out.toString('base64')}';\nexport const LAB_TARGET = ${JSON.stringify({ pageW: W, pageH: H, gratings })};\nexport const LAB_BUILD = '${process.env.GITHUB_SHA ?? 'local'}';\n`);
if (process.argv[2]) fs.writeFileSync(process.argv[2], out);
console.log(`Lab PDF: ${out.length} bytes, gratings ${BARS.join('/')} pt`);
