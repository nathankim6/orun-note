#!/usr/bin/env node
// Generate during development/build checks, never from Function.toString at app runtime.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const inputPath = path.join(root, 'src/features/viewer/reviewVideoSafety.ts');
const outputPath = path.join(root, 'src/features/viewer/reviewVideoPreferences.safe.generated.ts');

function buildPreferencesSource(input) {
  const source = ts.createSourceFile('reviewVideoSafety.ts', input, ts.ScriptTarget.ES2022, true, ts.ScriptKind.TS);
  if (source.parseDiagnostics.length) throw new Error('Preferences input contains syntax errors');
  const declarations = source.statements.filter(node => ts.isFunctionDeclaration(node) && node.name?.text === 'createPlayerPreferences');
  if (declarations.length !== 1 || !declarations[0].body) throw new Error('Expected one createPlayerPreferences declaration');
  const fn = declarations[0];
  const standalone = ts.factory.updateFunctionDeclaration(fn, fn.modifiers?.filter(modifier => modifier.kind !== ts.SyntaxKind.ExportKeyword && modifier.kind !== ts.SyntaxKind.DefaultKeyword), fn.asteriskToken, fn.name, fn.typeParameters, fn.parameters, fn.type, fn.body);
  const printed = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed, removeComments: true }).printNode(ts.EmitHint.Unspecified, standalone, source);
  const compiled = ts.transpileModule(printed, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: true, newLine: ts.NewLineKind.LineFeed }, reportDiagnostics: true });
  if (compiled.diagnostics?.some(diagnostic => diagnostic.category === ts.DiagnosticCategory.Error)) throw new Error('Preferences transpilation failed');
  const check = ts.createSourceFile('preferences.js', compiled.outputText, ts.ScriptTarget.ES2022, true, ts.ScriptKind.JS);
  const functions = check.statements.filter(node => ts.isFunctionDeclaration(node));
  const unexpected = check.statements.some(node => !ts.isFunctionDeclaration(node) && !(ts.isExpressionStatement(node) && ts.isStringLiteral(node.expression) && node.expression.text === 'use strict'));
  if (check.parseDiagnostics.length || functions.length !== 1 || unexpected) throw new Error('Expected only a standalone JavaScript function');
  const result = functions[0].getText(check).trim();
  if (/<\/script/i.test(result)) throw new Error('Preferences function must be safe inside an HTML script element');
  return result;
}
function buildGeneratedFile(input) {
  const source = buildPreferencesSource(input);
  return '// Generated by scripts/generate-review-video-preferences.js. DO NOT EDIT.\n// Source: reviewVideoSafety.ts createPlayerPreferences; static JavaScript for Hermes.\nexport const PLAYER_PREFERENCES_SOURCE = ' + JSON.stringify(source) + ';\n';
}
function main() {
  if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/generate-review-video-preferences.js [--check]');
  const expected = buildGeneratedFile(fs.readFileSync(inputPath, 'utf8'));
  if (process.argv.includes('--check')) {
    const actual = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
    if (actual !== expected) throw new Error('Generated native preferences are stale. Run node scripts/generate-review-video-preferences.js');
    console.log('PASS static native video preferences are current');
  } else {
    fs.writeFileSync(outputPath, expected);
    console.log('Generated ' + path.relative(root, outputPath));
  }
}
module.exports = { buildPreferencesSource, buildGeneratedFile };
if (require.main === module) { try { main(); } catch (error) { console.error(error.message); process.exitCode = 1; } }
